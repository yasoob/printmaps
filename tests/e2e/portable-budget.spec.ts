test('compact backups in replacement and real cross-tab conflict dialogs do not automatically replace either document', async ({ page }, testInfo) => {
  await page.goto('./');
  await openPortable(page, await portableFixture(page, 'boundary'));
  const dialog = await stagePortable(page, await admissionFixture(page));
  const replacing = page.waitForEvent('download');
  await dialog.getByRole('button', { name: 'Download current project' }).click();
  const replacementBackup = await portableDownload(await replacing, testInfo, 'replacement-backup');
  expect(replacementBackup.document.layers).toHaveLength(201);
  expect(replacementBackup.bytes).toBeLessThan(MAX_PROJECT_FILE_BYTES);
  expect(Buffer.byteLength(JSON.stringify(replacementBackup.document, null, 2))).toBeGreaterThan(MAX_PROJECT_FILE_BYTES);
  await expect(dialog).toBeVisible();
  await dialog.getByRole('button', { name: 'Keep editing' }).click();
  const winner = await page.context().newPage();
  await winner.goto('./');
  await winner.getByRole('combobox', { name: 'Page preset' }).selectOption('A3');
  await expect(winner.getByRole('status', { name: 'Autosave status' })).toHaveText('All changes saved locally', { timeout: 30_000 });
  const saved = await storedDraft(winner);
  await page.getByRole('combobox', { name: 'Page preset' }).selectOption('A5');
  await expect(page.getByRole('status', { name: 'Autosave conflict notice' })).toBeVisible();
  const conflict = await reviewConflict(page);
  const backingUp = page.waitForEvent('download');
  await conflict.getByRole('button', { name: 'Download this tab’s version' }).click();
  const backup = await portableDownload(await backingUp, testInfo, 'conflict-backup');
  expect(backup.document.page.preset).toBe('A5');
  expect(backup.document.layers).toHaveLength(201);
  expect(backup.bytes).toBeLessThan(MAX_PROJECT_FILE_BYTES);
  await expect(conflict).toBeVisible();
  await expect(page.getByRole('status', { name: 'Conflict download status' })).toContainText('Download started');
  expect(await storedDraft(winner)).toEqual(saved);
  await page.screenshot({ path: testInfo.outputPath('ux-fix-029-compact-conflict.png'), animations: 'disabled' });
});

