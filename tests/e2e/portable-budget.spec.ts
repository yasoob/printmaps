test('actual 160200-position import autosaves, downloads compact losslessly, and reopens', async ({ page }, testInfo) => {
  await page.goto('./');
  await openPortable(page, await admissionFixture(page));
  const source = await portableBoundarySource(page);
  await importSingleGeoJson(page, source);
  await expect(page.locator('.layer-row')).toHaveCount(201);
  await expect(page.getByRole('status', { name: 'Autosave status' })).toHaveText('All changes saved locally', { timeout: 30_000 });
  const saved = await savedAdmissionRecord(page);
  const downloaded = await downloadPortable(page, testInfo, '160200-boundaries');
  const readableBytes = Buffer.byteLength(JSON.stringify(downloaded.document, null, 2) + '\n');
  expect(readableBytes).toBeGreaterThan(MAX_PROJECT_FILE_BYTES);
  expect(downloaded.bytes).toBeLessThan(MAX_PROJECT_FILE_BYTES);
  expect(downloaded.bytes).toBe(Buffer.byteLength(JSON.stringify(downloaded.document)));
  expect(downloaded.document.layers).toEqual(saved.document.layers);
  expect(await assertFreshPortable(page, downloaded.text)).toMatchObject({ layers: 201 });
  const sourceBytes = Buffer.byteLength(JSON.stringify(source));
  await testInfo.attach('ux-fix-029-original-measurements', { body: JSON.stringify({
    sourceBytes, compactBytes: downloaded.bytes,
    readableBytes, layerCount: 201, positions: 160_200,
  }), contentType: 'application/json' });
  await page.screenshot({ path: testInfo.outputPath('ux-fix-029-boundary-download.png'), animations: 'disabled' });
  await openPortable(page, downloaded.document);
  const reopened = await savedAdmissionRecord(page);
  expect(reopened.document.layers).toEqual(downloaded.document.layers);
  await page.reload();
  await expect(page.locator('.layer-row')).toHaveCount(201);
});

