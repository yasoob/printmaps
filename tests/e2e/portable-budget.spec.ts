  expect(prompt.type()).toBe('beforeunload');
  await prompt.dismiss(); await reloading;
  await expect(page.getByRole('status', { name: 'Area drawing status' })).toHaveText('3 vertices');
  expect(await savedAdmissionRecord(page)).toEqual(saved);
  await page.screenshot({ path: testInfo.outputPath('ux-fix-029-area-retained.png'), animations: 'disabled' });
