test('native camera rejection restores map, diagnostics and redo; interrupted renderer recovery cannot revive a rejected viewport', async ({ page }, testInfo) => {
  await openInstrumentedMap(page);
  const full = await portableFixture(page);
  await openPortable(page, full);
  await expect(page.getByTestId('map-canvas')).toHaveAttribute('data-map-ready', 'true', { timeout: 30_000 });
  await page.getByLabel('Bearing', { exact: true }).fill('1');
  await page.getByLabel('Bearing', { exact: true }).press('Tab');
  await page.getByRole('button', { name: 'Undo', exact: true }).click();
  await expect(page.getByRole('status', { name: 'Autosave status' })).toHaveText('All changes saved locally');
  await expect(page.getByRole('button', { name: 'Redo', exact: true })).toBeEnabled();
  const saved = await savedAdmissionRecord(page), before = await portableCameraSnapshot(page);
  await trackWrites(page);
  await page.evaluate(() => window.recoveryAudit.map!.jumpTo({ center: [16.123456, 48.123456], zoom: 13.123456, bearing: 30, pitch: 20 }));
  await expect(page.getByRole('alert', { name: 'Camera change not saved' })).toContainText('Previous map view restored');
  expect(normalizedViewport(await portableCameraSnapshot(page))).toEqual(normalizedViewport(saved.document.camera));
  await expect(page.getByTestId('map-canvas')).toHaveAttribute('data-map-center', saved.document.camera.center.join(','));
  await expect(page.getByTestId('map-canvas')).toHaveAttribute('data-map-zoom', String(saved.document.camera.zoom));
  await expect(page.getByRole('button', { name: 'Redo', exact: true })).toBeEnabled();
  const rejected = await portableCameraSnapshot(page);
  expect(rejected.rendererCount).toBe(before.rendererCount);
  await assertUnobstructedSearch(page);
  await page.screenshot({ path: testInfo.outputPath('ux-fix-029-native-camera-rollback.png'), animations: 'disabled' });
  const interrupted = await loseOversizedCameraMove(page);
  const interruptedBytes = Buffer.byteLength(JSON.stringify({ ...saved.document, camera: { ...saved.document.camera, ...normalizedViewport(interrupted) } }));
  expect(interruptedBytes).toBeGreaterThan(MAX_PROJECT_FILE_BYTES);
  await expect(page.getByRole('button', { name: 'Retry map' })).toBeEnabled();
  await page.getByRole('button', { name: 'Retry map' }).click();
  await expect(page.getByTestId('map-canvas')).toHaveAttribute('data-map-ready', 'true', { timeout: 30_000 });
  const recovered = await portableCameraSnapshot(page);
  expect(normalizedViewport(recovered)).toEqual(normalizedViewport(saved.document.camera));
  expect(recovered.rendererCount).toBe(before.rendererCount + 1);
  await expect(page.getByRole('button', { name: 'Redo', exact: true })).toBeEnabled();
  expect(await savedAdmissionRecord(page)).toEqual(saved);
  expect(await page.evaluate(() => window.conflictInstrumentation.puts)).toBe(0);
  await testInfo.attach('ux-fix-029-camera-evidence', { body: JSON.stringify({ canonical: saved.document.camera, before, interrupted, interruptedBytes, recovered }), contentType: 'application/json' });
  await page.screenshot({ path: testInfo.outputPath('ux-fix-029-recovery-canonical.png'), animations: 'disabled' });
});

