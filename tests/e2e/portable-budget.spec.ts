  await expect(page.locator('.map-route-editor-error')).toContainText('portable limit');
  const restored = await marker.boundingBox();
  expect(Math.hypot(restored!.x - before!.x, restored!.y - before!.y)).toBeLessThan(1);
  await page.getByRole('button', { name: 'Area (S)' }).click();
